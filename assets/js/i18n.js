/**
 * Detect default language based on browser preferences.
 * Default is 'en'. If browser indicates Russian / CIS language, returns 'ru'.
 */
export function detectBrowserLanguage() {
  const saved = localStorage.getItem("mut3_lang");
  if (saved === "ru" || saved === "en") {
    return saved;
  }
  const languages = navigator.languages || [navigator.language || ""];
  const cisLangs = ["ru", "be", "uk", "kk"];
  for (const lang of languages) {
    if (!lang) continue;
    const code = lang.toLowerCase().split("-")[0].split("_")[0];
    if (cisLangs.includes(code)) {
      return "ru";
    }
    if (code === "en") {
      return "en";
    }
  }
  return "en"; // Default is English per requirements
}
